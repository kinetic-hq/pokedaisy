#!/usr/bin/env python3
"""Writes 3ds/core/pd_font_faces_gen.c: the wings' two extra faces as 1-bit bitmap fonts in pd_font.h's cells.

- Headings: Silkscreen Bold (third_party/fonts/silkscreen, SIL OFL 1.1), drawn on its own 2-pixel grid at 16 px,
  caps sitting on Pixel Operator's baseline (row 13).
- Numbers: Atkinson Hyperlegible Bold (app/src/main/assets/fonts, SIL OFL 1.1) at 14 px, figures and the few marks
  that go with them; anything else falls back to Pixel Operator.

    python3 3ds/tools/gen_font_faces.py      (needs Pillow)
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
HEADING_TTF = os.path.join(ROOT, "third_party/fonts/silkscreen/Silkscreen-Bold.ttf")
NUMBER_TTF = os.path.join(ROOT, "app/src/main/assets/fonts/AtkinsonHyperlegible-Bold.ttf")
OUT = os.path.join(ROOT, "3ds/core/pd_font_faces_gen.c")
CELL = 16
BASELINE = 13  # Pixel Operator's: caps on rows 4-12
SCALE = 10


def raster(font, ch, dy, threshold):
    im = Image.new("L", (CELL * SCALE, CELL * SCALE), 0)
    ImageDraw.Draw(im).text((0, dy), ch, font=font, fill=255)
    rows = [0] * CELL
    for y in range(CELL):
        for x in range(CELL):
            if im.getpixel((x * SCALE + SCALE // 2, y * SCALE + SCALE // 2)) > threshold:
                rows[y] |= 1 << x
    return rows


def face(name, ttf, size, chars, threshold, tighten):
    font = ImageFont.truetype(ttf, size * SCALE)
    # Put the bottom of 'H' / '0' on the baseline row.
    probe = "H" if "H" in chars else "0"
    bottom = font.getbbox(probe)[3]
    dy = BASELINE * SCALE - bottom
    lines = [f"const struct pd_glyph {name}[{len(chars)}] = {{"]
    for ch in chars:
        advance = max(1, round(font.getlength(ch) / SCALE) - tighten)
        rows = raster(font, ch, dy, threshold)
        assert all(r < (1 << CELL) for r in rows)
        desc = "space" if ch == " " else ch.replace("\\", "backslash")
        lines.append(f"    {{ 0x{ord(ch):04X}, {advance}, {{ {', '.join(f'0x{r:04X}' for r in rows)} }} }}, // {desc}")
    lines.append("};")
    lines.append(f"const int {name}_count = {len(chars)};")
    return lines


def main():
    heading = [chr(c) for c in range(32, 127) if chr(c) not in "\\`"]
    numbers = list("0123456789/:$%+-.,")
    out = [
        "// Generated by 3ds/tools/gen_font_faces.py from Silkscreen Bold and Atkinson Hyperlegible Bold (SIL OFL 1.1)",
        "// - do not hand-edit.",
        '#include "pd_font.h"',
        "",
    ]
    out += face("pd_font_heading", HEADING_TTF, 16, heading, 127, 2)
    out.append("")
    out += face("pd_font_numbers", NUMBER_TTF, 14, numbers, 110, 0)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
